def split_modes(lam: list) -> tuple:
    """(slow, fast) eigenvalue of one point; for a complex pair: (+Im member, -Im member)."""
    a, b = lam
    if abs(a.imag) > 1e-12:
        return (a, b) if a.imag > 0 else (b, a)
    return (a, b) if abs(a.real) <= abs(b.real) else (b, a)


def fig_eigen_map(l1: dict) -> None:
    sls, cr = ops(l1)
    fig, ax = plt.subplots(figsize=(6.3, 3.6))
    for gi, (g, name) in enumerate(((sls, "SLS (sea level, static)"), (cr, "35,000 ft, Mach 0.8"))):
        lam = [[cplx(l) for l in p["lam"]] for p in g]
        slow, fast = np.array([split_modes(r)[0] for r in lam]), np.array([split_modes(r)[1] for r in lam])
        ax.plot(slow.real, slow.imag, label=name + ": slow mode", **sty(2 * gi))
        ax.plot(fast.real, fast.imag, label=name + ": fast mode", **sty(2 * gi + 1))
        for z, txt in ((slow[0], "idle"), (slow[-1], "max")):
            ax.annotate(txt, (z.real, z.imag), textcoords="offset points", xytext=(4, 5), fontsize=7, color=INK2)
    ax.axvline(0, color=INK2, lw=0.8)
    ax.set_xlabel("Re($\\lambda$)  [1/s]")
    ax.set_ylabel("Im($\\lambda$)  [1/s]")
    ax.set_title("Eigenvalues of A from idle to max power (AGTF30 port); all in the left half-plane = stable\n"
                 "(a complex pair is drawn as slow = +Im, fast = -Im: the two modes merge into one oscillatory pair)", fontsize=8)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.16), ncol=2)
    save(fig, "eigen_map_complex_plane")


