def fig_fd(l2: dict) -> None:
    for start in ("converged", "offset"):
        for scheme in ("forward", "central"):
            pts = [s for s in l2["points"] if s["start"] == start]
            if not pts:
                continue
            n = len(pts)
            cols = 2 if n > 1 else 1
            rows_ = math.ceil(n / cols)
            fig, axes = plt.subplots(rows_, cols, figsize=(6.6, 2.6 * rows_), squeeze=False)
            for ax, s in zip(axes.ravel(), pts):
                for i, tol in enumerate(sorted(s["tols"], key=float)):
                    r = s["tols"][tol]
                    e = np.array([nan(v) for v in r[scheme]])
                    ax.loglog(s["h"], e, label="tol = %s" % tol, **sty(i))
                    ax.plot([r[scheme + "_h_opt"]], [r[scheme + "_err_min"]], marker=MARKERS[i], ms=9, mfc="none",
                            mec=COLORS[i], ls="none")
                ax.set_title(s["label"], fontsize=8)
                ax.set_xlabel("relative step h [-]")
                ax.set_ylabel(r"max $|\lambda_{FD}-\lambda_{ref}|/|\lambda_{ref}|$")
            for ax in axes.ravel()[n:]:
                ax.axis("off")
            hdl, lab = axes.ravel()[0].get_legend_handles_labels()
            fig.suptitle("%s-difference eigenvalue error vs step h (%s inner-solver start); open marker = best h"
                         % (scheme.capitalize(), start), fontsize=9)
            fig.tight_layout(rect=(0, 0.05, 1, 1))
            fig.legend(hdl, lab, loc="lower center", ncol=4)
            save(fig, "fd_error_vs_h_%s_%s" % (scheme, start))


