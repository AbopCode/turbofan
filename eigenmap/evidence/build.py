TABLE_SET: dict[str, tuple[list, list]] = {}


def table(name: str, header: list, rows: list, caption: str) -> None:
    """Write <name>.csv and <name>.tex (plain tabular, no extra packages) and keep it for the xlsx."""
    TABLES.mkdir(parents=True, exist_ok=True)
    with open(TABLES / (name + ".csv"), "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow([_cell(c) for c in r])
    esc = lambda s: str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")
    lines = [r"% generated by eigenmap.evidence.build from outputs/data - do not edit",
             r"\begin{table}[htbp]\centering\small", r"\caption{%s}" % esc(caption), r"\label{tab:%s}" % name,
             r"\begin{tabular}{%s}" % ("l" * len(header)), r"\hline", " & ".join(esc(h) for h in header) + r" \\", r"\hline"]
    for r in rows:
        lines.append(" & ".join(esc(_cell(c)) for c in r) + r" \\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}", ""]
    (TABLES / (name + ".tex")).write_text("\n".join(lines))
    TABLE_SET[name] = (header, rows)
    written.append("tables/%s.csv" % name)


def _cell(c):
    if isinstance(c, float):
        if c != c:
            return "n/a"
        a = abs(c)
        return "%.6g" % c if (a == 0 or 1e-3 <= a < 1e6) else "%.3e" % c
    return c


def write_xlsx() -> None:
    try:
        from openpyxl import Workbook
    except ImportError:
        return
    wb = Workbook()
    wb.remove(wb.active)
    for name, (header, rows) in TABLE_SET.items():
        ws = wb.create_sheet(name[:31])
        ws.append(header)
        for r in rows:
            ws.append([c if not (isinstance(c, float) and c != c) else None for c in r])
    import datetime as _dt
    fixed = _dt.datetime(2026, 1, 1)
    wb.properties.created = fixed
    wb.properties.modified = fixed
    wb.properties.creator = "eigenmap"
    wb.save(TABLES / "tables.xlsx")
    # an .xlsx is a zip archive whose entries carry the time of writing: rewrite them with a fixed date (reproducible bytes)
    import io
    import zipfile
    src = (TABLES / "tables.xlsx").read_bytes()
    buf = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(src)) as zin, zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zout:
        for info in zin.infolist():
            data = zin.read(info.filename)
            if info.filename == "docProps/core.xml":      # remove any remaining timestamps
                import re as _re
                data = _re.sub(rb"(<dcterms:(created|modified)[^>]*>)[^<]*(</dcterms:)", rb"\g<1>2026-01-01T00:00:00Z\g<3>", data)
            zi = zipfile.ZipInfo(info.filename, date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zout.writestr(zi, data)
    (TABLES / "tables.xlsx").write_bytes(buf.getvalue())


