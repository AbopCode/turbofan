def sty(i: int, line: bool = True) -> dict:
    """Style of series i: color + marker + line style, all three, so print in black and white still works."""
    d = {"color": COLORS[i % 8], "marker": MARKERS[i % 8], "markersize": 4.5, "markeredgewidth": 0.6,
         "markeredgecolor": "white"}
    d["linestyle"] = LINES[i % 8] if line else "none"
    return d


def save(fig, name: str) -> None:
    FIGS.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGS / (name + ".png"), dpi=300, metadata={"Software": None})
    fig.savefig(FIGS / (name + ".svg"), metadata={"Date": None, "Creator": None})
    plt.close(fig)
    written.append("figures/%s.png" % name)


def load(name: str) -> dict | None:
    p = DATA / (name + ".json")
    return json.loads(p.read_text()) if p.exists() else None


def cplx(v) -> complex:
    return complex(v[0], v[1]) if isinstance(v, list) else complex(v)


def fmt_lam(v) -> str:
    z = cplx(v)
    return "%.4f" % z.real if abs(z.imag) < 1e-12 else "%.4f%+.4fi" % (z.real, z.imag)


def nan(v) -> float:
    return float("nan") if v is None else float(v)


